let customJs = fs.readFileSync('data-custom-translations.js', 'utf8');

['de', 'en', 'fr', 'it', 'es', 'el'].forEach(lang => {
  const langKey = `  "${lang}": {`;
  const insertIndex = customJs.indexOf(langKey);
  if (insertIndex !== -1) {
    const afterKeyIndex = insertIndex + langKey.length;
    let newEntries = '\n';
    Object.entries(mobileAdditions[lang]).forEach(([k, v]) => {
      newEntries += `    "${k}": ${JSON.stringify(v)},\n`;
    });
    customJs = customJs.slice(0, afterKeyIndex) + newEntries + customJs.slice(afterKeyIndex);
  }
});

fs.writeFileSync('data-custom-translations.js', customJs, 'utf8');
